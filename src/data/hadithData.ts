/**
 * Helper to get all hadiths of a specific book
 */
export function getHadithsByBook(bookId: string): SahihHadithItem[] {
  if (bookId === 'all') return SAHIH_HADITH_COLLECTION;
  return SAHIH_HADITH_COLLECTION.filter((h) => h.bookId === bookId);
}

/**
 * Helper to get unique chapters of a book
 */
export function getBookChapters(bookId: string): string[] {
  const hadiths = getHadithsByBook(bookId);
  const chapters = Array.from(new Set(hadiths.map((h) => h.chapterBn)));
  return chapters;
}
